export type IconName = keyof typeof ICONS;

/** An SVG path for a bitmap: one rectangle per run of lit pixels in a row. */
export function pixels(rows: readonly string[]): string {
  let d = "";
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1H${m.index}z`;
  });
  return d;
}
